export interface TaxOfficeSuggestion {
  city: string;
  code: string;
  name: string;
}

const CITY_NAMES_BY_CODE = new Map(TR_CITIES);

const OFFICES: ReadonlyArray<TaxOfficeSuggestion> = TAX_OFFICES.map(([code, name]) => ({
  city: CITY_NAMES_BY_CODE.get(code.slice(0, 2)) ?? '',
  code,
  name,
}));

/**
 * The tax offices to suggest for `query`. When `city` names an il, its own
 * offices (all of them for an empty query); otherwise the offices whose name
 * or il starts with the typed words, and none before something is typed.
 * GİB's order, at most `limit`.
 */
export function suggestTaxOffices(query: string, city: string, limit = 50) {
  const code = cityCode(city);
  if (!code && !query.trim()) {
    return [];
  }
  return OFFICES.filter((office) =>
    code
      ? office.code.startsWith(code) && matchesWords(query, office.name)
      : matchesWords(query, office.name, office.city),
  ).slice(0, limit);
}
